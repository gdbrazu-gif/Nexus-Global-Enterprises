// Helper to pre-populate current month timesheet (e.g., October 2026)
export const generateInitialTimesheet = (): TimesheetEntry[] => {
  const entries: TimesheetEntry[] = [];
  const year = 2026;
  const month = 10; // October
  const daysInMonth = 31;

  INITIAL_EMPLOYEES.forEach((emp) => {
    for (let day = 1; day <= daysInMonth; day++) {
      const dateStr = `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
      const d = new Date(year, month - 1, day);
      const dayOfWeek = d.getDay(); // 5 = Friday, 6 = Saturday in standard JS
      const isWeekend = dayOfWeek === 5 || dayOfWeek === 6; // Friday & Saturday weekend

      let status: TimesheetEntry['status'] = 'present';
      let regularHours = 8;
      let overtimeHours = 0;
      let notes = 'Standard shift';

      if (isWeekend) {
        status = 'weekend';
        regularHours = 0;
        overtimeHours = 0;
        notes = 'Weekend (Fri/Sat)';
      } else {
        // Deterministic variation for realistic demonstration
        if (day === 8 && emp.id === 'EMP-1005') {
          status = 'overtime';
          regularHours = 8;
          overtimeHours = 3;
          notes = 'Cloud infrastructure migration overtime';
        } else if (day === 12 && emp.id === 'EMP-1006') {
          status = 'annual_leave';
          regularHours = 0;
          notes = 'Approved annual leave';
        } else if (day === 13 && emp.id === 'EMP-1006') {
          status = 'annual_leave';
          regularHours = 0;
          notes = 'Approved annual leave';
        } else if (day === 18 && emp.id === 'EMP-1007') {
          status = 'sick_leave';
          regularHours = 0;
          notes = 'Medical leave documented';
        } else if (day === 15 && emp.id === 'EMP-1008') {
          status = 'overtime';
          regularHours = 8;
          overtimeHours = 2;
          notes = 'Quarterly VAT closing';
        } else if (day === 22 && emp.id === 'EMP-1004') {
          status = 'overtime';
          regularHours = 8;
          overtimeHours = 2.5;
          notes = 'Steering committee preparation';
        }
      }

      entries.push({
        id: `TS-${emp.id}-${dateStr}`,
        employeeId: emp.id,
        date: dateStr,
        regularHours,
        overtimeHours,
        status,
        notes,
        updatedBy: 'System Auto-Ledger',
        updatedAt: '2026-10-01T08:00:00Z',
      });
    }
  });

  return entries;
};

